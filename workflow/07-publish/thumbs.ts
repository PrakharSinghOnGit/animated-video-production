import { runAgentAsync } from "../05-video/src/lib/agent";
import { roleModel } from "../lib/models";
import { loadPrompt } from "../learning/lessons";
import { recordTiming, formatDuration } from "../05-video/src/lib/timings";
import { REPO, VARIANTS, GUIDE, THUMB_MAX_BYTES, THUMB_MAX_WORDS, THUMB_W, THUMB_H, wsDir, pubDir, pubFile, readJson, readText, videoSeconds, badgeTime, planNumbers, numberProblems, thumbPath, type Metadata, type ThumbInfo, type Variant } from "./lib";

const args = process.argv.slice(2);
const flag = (n: string) => { const i = args.indexOf(n); return i >= 0 ? args[i + 1] : undefined; };
const videoId = flag("--video") ?? flag("-v");
const model = roleModel("thumbs", flag("--model"));
const only = flag("--variant")?.toUpperCase();
const renderOnly = args.includes("--render-only");
const fixMode = args.includes("--notes");
const force = args.includes("--force");
const noPreview = args.includes("--no-preview");
if (!videoId || (only && !VARIANTS.includes(only as Variant))) {
  console.error("Usage: bun run thumbs --video <ID> [--variant A|B|C] [--notes] [--model sonnet|opus|haiku] [--force]\n       bun run thumbs:render --video <ID> [--variant A] [--no-preview]");
  process.exit(1);
}
const ws = wsDir(videoId);
if (!fs.existsSync(ws)) { console.error(`❌ no workspace ${ws}`); process.exit(1); }
const pub = pubDir(videoId), rem = path.join(pub, "remotion"), thumbsDir = path.join(rem, "thumbs"), outDir = path.join(pub, "thumbnails");
const chosen: Variant[] = only ? [only as Variant] : [...VARIANTS];
const srcFile = (v: string) => path.join(thumbsDir, `${v}.tsx`);

/** Project files: copies of the template (when they differ), the generated entry and registry. */
function syncProject(): void {
  fs.mkdirSync(thumbsDir, { recursive: true });
  fs.mkdirSync(outDir, { recursive: true });
  for (const f of ["Root.tsx", "Preview.tsx"]) {
    const from = path.join(REPO, "workflow/07-publish/template", f), to = path.join(rem, f);
    if (!fs.existsSync(to) || fs.readFileSync(to, "utf-8") !== fs.readFileSync(from, "utf-8")) fs.copyFileSync(from, to);
  }
  const write = (f: string, text: string) => { const p = path.join(rem, f); if (readText(p) !== text) fs.writeFileSync(p, text); };
  write("index.ts", `import { registerRoot } from "remotion";\nimport { RemotionRoot } from "./Root";\n\nregisterRoot(RemotionRoot);\n`);
  const have = VARIANTS.filter((v) => fs.existsSync(srcFile(v)));
  write("registry.ts", `/** Generated by thumbs.ts from the files in thumbs/ */\nimport React from "react";\n${have.map((v) => `import ${v} from "./thumbs/${v}";`).join("\n")}\n\nexport const THUMBS: Record<string, React.ComponentType> = { ${have.join(", ")} };\n`);
}

const ffprobe = (p: string): { w: number; h: number } | null => {
  const r = spawnSync("ffprobe", ["-v", "error", "-select_streams", "v:0", "-show_entries", "stream=width,height", "-of", "csv=p=0", p], { encoding: "utf-8" });
  const [w, h] = r.stdout.trim().split(",").map(Number);
  return w && h ? { w, h } : null;
};

/** PNG as rendered; when it passes 2 MB, a high-quality JPG instead (YouTube takes either). Returns the final file. */
function fitSize(v: string, png: string): string {
  const jpg = path.join(outDir, `${v}.jpg`);
  fs.rmSync(jpg, { force: true });
  if (fs.statSync(png).size <= THUMB_MAX_BYTES) return png;
  for (const q of ["2", "4", "6"]) {
    spawnSync("ffmpeg", ["-y", "-v", "error", "-i", png, "-q:v", q, jpg]);
    if (fs.existsSync(jpg) && fs.statSync(jpg).size <= THUMB_MAX_BYTES) { fs.rmSync(png); return jpg; }
  }
  fs.rmSync(png, { force: true });
  return fs.existsSync(jpg) ? jpg : png;
}

const chromiumOptions = { gl: "angle" as const };

/** Render the chosen variants (and then the preview sheets). Returns per-variant error text; never throws on a bad thumb file. */
async function render(vs: Variant[], preview: boolean): Promise<Record<string, string>> {
  syncProject();
  const errors: Record<string, string> = {};
  const todo = vs.filter((v) => fs.existsSync(srcFile(v)));
  for (const v of vs) if (!todo.includes(v)) errors[v] = `thumbs/${v}.tsx does not exist`;
  if (todo.length) {
    const t0 = Date.now();
    console.log(`📦 Bundling the thumbnail project...`);
    let serveUrl: string;
    try { serveUrl = await bundle({ entryPoint: path.join(rem, "index.ts") }); }
    catch (e: any) { for (const v of todo) errors[v] = `bundle failed: ${String(e?.message ?? e).slice(0, 1500)}`; return errors; }
    for (const v of todo) {
      const out = path.join(outDir, `${v}.png`);
      try {
        const composition = await selectComposition({ serveUrl, id: `T${v}`, inputProps: {}, chromiumOptions, logLevel: "error" });
        await renderStill({ serveUrl, composition, frame: 0, output: out, imageFormat: "png", chromiumOptions, logLevel: "error", overwrite: true });
        const final = fitSize(v, out);
        const dim = ffprobe(final);
        console.log(`🖼  ${v}: ${path.relative(REPO, final)} ${dim ? `${dim.w}x${dim.h}` : ""} ${(fs.statSync(final).size / 1024).toFixed(0)} KB`);
      } catch (e: any) { errors[v] = String(e?.message ?? e).slice(0, 1500); console.error(`❌ ${v}: ${errors[v]}`); }
    }
    console.log(`   stills in ${formatDuration(Date.now() - t0)}`);
  }
  if (preview) await renderPreviews();
  return errors;
}

/** preview.png (large + 320 + 168 + feed cards, light and dark) and preview_small.png, from the thumbnails that exist. */
async function renderPreviews(): Promise<void> {
  const meta = readJson<Metadata>(pubFile(videoId!, "metadata.json"));
  const packages = VARIANTS.flatMap((v) => {
    const p = thumbPath(videoId!, v);
    return p ? [{ id: v, file: path.basename(p), title: meta?.titles?.[v]?.title ?? "", type: meta?.titles?.[v]?.type ?? "" }] : [];
  });
  if (!packages.length) return;
  const inputProps = { packages, duration: badgeTime(videoSeconds(videoId!)), channel: "The Wealth Gap" };
  try {
    const serveUrl = await bundle({ entryPoint: path.join(rem, "index.ts"), publicDir: outDir });
    for (const [id, file] of [["Preview", "preview.png"], ["PreviewSmall", "preview_small.png"]]) {
      const composition = await selectComposition({ serveUrl, id, inputProps, chromiumOptions, logLevel: "error" });
      await renderStill({ serveUrl, composition, frame: 0, output: path.join(pub, file), imageFormat: "png", inputProps, chromiumOptions, logLevel: "error", overwrite: true });
    }
    console.log(`🗂  preview.png, preview_small.png`);
  } catch (e: any) { console.error(`❌ preview failed: ${String(e?.message ?? e).slice(0, 1500)}`); }
}

/** Mechanical checks on what the author declared and what was rendered; written to thumbnails.checks.json for the dashboard. */
function check(): Record<string, { errors: string[]; warnings: string[] }> {
  const info = readJson<Record<string, ThumbInfo>>(pubFile(videoId!, "thumbnails.json")) ?? {};
  const meta = readJson<Metadata>(pubFile(videoId!, "metadata.json"));
  const pn = planNumbers(readJson(path.join(ws, "05-video/acts.json")));
  const out: Record<string, { errors: string[]; warnings: string[] }> = {};
  for (const v of VARIANTS) {
    const errors: string[] = [], warnings: string[] = [], p = thumbPath(videoId!, v);
    out[v] = { errors, warnings };
    if (!p) { errors.push("not rendered"); continue; }
    const size = fs.statSync(p).size, dim = ffprobe(p);
    if (size > THUMB_MAX_BYTES) errors.push(`${(size / 1048576).toFixed(2)} MB (max 2 MB)`);
    if (!dim || dim.w !== THUMB_W || dim.h !== THUMB_H) errors.push(`size is ${dim ? `${dim.w}x${dim.h}` : "unknown"}, expected ${THUMB_W}x${THUMB_H}`);
    const i = info[v];
    if (!i) { warnings.push("thumbnails.json has no entry (concept, text and numbers are not declared)"); continue; }
    const words = (i.text ?? "").trim().split(/\s+/).filter(Boolean);
    if (words.length > THUMB_MAX_WORDS) errors.push(`${words.length} words of text (max ${THUMB_MAX_WORDS})`);
    const np = numberProblems([i.text ?? "", ...(i.numbers ?? [])].join(" "), pn);
    if (np.missing.length) errors.push(`number ${[...new Set(np.missing)].join(", ")} is not in the plan's data`);
    if (np.unverified.length) warnings.push(`number ${[...new Set(np.unverified)].join(", ")} is only sourced from the narration: fact-check it`);
    const title = meta?.titles?.[v]?.title ?? "";
    const tw = new Set(title.toLowerCase().replace(/[^a-z0-9% ]+/g, " ").split(/\s+/).filter((w) => w.length > 2));
    const dup = words.map((w) => w.toLowerCase().replace(/[^a-z0-9%]+/g, "")).filter((w) => w.length > 2 && tw.has(w));
    if (words.length && dup.length === words.length) errors.push(`the text repeats the title ("${i.text}")`);
    else if (dup.length) warnings.push(`the text shares "${dup.join(", ")}" with the title`);
  }
  fs.writeFileSync(pubFile(videoId!, "thumbnails.checks.json"), JSON.stringify(out, null, 2));
  return out;
}

function report(errs: Record<string, string>) {
  const c = check();
  for (const v of VARIANTS) {
    const r = c[v];
    if (errs[v]) console.log(`   ✗ ${v}: ${errs[v].split("\n")[0]}`);
    for (const e of r.errors) console.log(`   ✗ ${v}: ${e}`);
    for (const w of r.warnings) console.log(`   ⚠ ${v}: ${w}`);
  }
}

