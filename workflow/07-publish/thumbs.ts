/**
 * Publish: the three thumbnails (paid), drawn as Briefing-kit stills, rendered with Remotion, plus the preview sheets.
 *
 * Usage: bun run thumbs --video <ID> [--variant A|B|C] [--notes] [--model sonnet|opus|haiku] [--force]
 *        bun run thumbs:render --video <ID> [--variant A] [--no-preview]      (free: render the PNGs + previews from the TSX)
 *   default   the author designs the variants that have no file yet (--force: all of the chosen ones)
 *   --notes   fix mode: re-authors the variants that have notes (07-publish/notes/<V>.md), resuming the author's session
 *   --variant only this variant
 *
 * Registration: thumbnails are NOT scenes of the 05-video project, so assemble.ts's template sync (which rewrites
 * Root.tsx/Main.tsx there) cannot touch them. They live in their own Remotion project, workspace/<ID>/07-publish/remotion/:
 * index.ts (registerRoot) and registry.ts are generated here from the files in thumbs/, Root.tsx + Preview.tsx are synced
 * from workflow/07-publish/template/, and thumbs/<V>.tsx are the authored stills. Same node_modules resolution as 05-video
 * (the workspace sits under the repo), same renderer options (--gl=angle as chromiumOptions.gl).
 * The brief is workflow/prompts/THUMBS.md; the rules are workflow/07-publish/GUIDE.md.
 */
