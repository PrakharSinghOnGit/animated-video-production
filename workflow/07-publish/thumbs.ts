/** The author's latest session (from its logs), so a fix round reuses its context. */
function lastSession(): string | undefined {
  const dir = pubFile(videoId!, "logs");
  const logs = fs.readdirSync(dir).filter((f) => /^thumbs_\d+\.log$/.test(f)).sort((a, b) => parseInt(a.slice(7)) - parseInt(b.slice(7)));
  for (const f of logs.reverse()) { const m = readText(path.join(dir, f)).match(/"session_id":"([^"]+)"/); if (m) return m[1]; }
  return undefined;
}
